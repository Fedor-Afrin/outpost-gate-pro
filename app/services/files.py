FSTYPES = {"ext4", "ext3", "ext2", "xfs", "btrfs", "ntfs", "ntfs3", "exfat", "vfat"}
FOREIGN_FS = {"ntfs", "ntfs3", "exfat", "vfat"}          # без Unix-прав: владелец задаётся при монтировании

_smbd = ManagedProcess("smbd")
_nmbd = ManagedProcess("nmbd")
_lock = threading.RLock()


class FilesError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status
        self.message = message


def _data(*parts: str) -> Path:
    return Path(settings.data_dir).joinpath("samba", *parts)


def data_volume() -> Path:
    return Path(settings.data_dir) / "shares"


def disks_allowed() -> bool:
    return os.getenv("ROUTER_DISKS", "1" if settings.mode == "host" else "0") == "1"


def _run(cmd: list[str], input: str | None = None, timeout: int = 60, check: bool = True) -> subprocess.CompletedProcess:
    try:
        r = subprocess.run(cmd, input=input, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError as e:
        raise FilesError(500, f"нет программы {cmd[0]} — пересоберите образ") from e
    except subprocess.TimeoutExpired as e:
        raise FilesError(500, f"{cmd[0]}: нет ответа за {timeout} с") from e
    if check and r.returncode != 0:
        msg = " ".join((r.stderr or r.stdout).split())[-300:]
        raise FilesError(400, f"{cmd[0]}: {msg or f'код {r.returncode}'}")
    return r


# --- конфиг ----------------------------------------------------------------------------------
def get_config() -> FilesConfig:
    return FilesConfig.model_validate(store.load().get("files") or {})


def _save(cfg: FilesConfig) -> None:
    with store.transaction() as data:
        data["files"] = cfg.to_yaml()


def netbios_name(cfg: FilesConfig) -> str:
    if cfg.netbios_name:
        return cfg.netbios_name
    ident = (store.load().get("system") or {}).get("identity") or "outpost"
    return (re.sub(r"[^A-Za-z0-9-]", "-", ident).strip("-") or "OUTPOST")[:15].upper()


def assign_ids(cfg: FilesConfig) -> FilesConfig:
    """Выдать uid/gid новым пользователям и группам: стабильно, из своего диапазона."""
    c = cfg.model_copy(deep=True)
    used = {u.uid for u in c.users if u.uid} | {g.gid for g in c.groups if g.gid}
    nxt = FIRST_UID
    for item, attr in [(u, "uid") for u in c.users] + [(g, "gid") for g in c.groups]:
        if getattr(item, attr):
            continue
        while nxt in used:
            nxt += 1
        setattr(item, attr, nxt)
        used.add(nxt)
    return c


def _segments(cfg: FilesConfig):
    from app.services import lan
    segs = [s for s in lan.segments() if s.enabled]
    if cfg.segments:
        segs = [s for s in segs if s.id in cfg.segments]
    return segs


def volume_path(name: str) -> Path:
    return data_volume() if name == "data" else DISKS_ROOT / name


def share_path(share) -> Path:
    return volume_path(share.volume) / share.folder


# --- smb.conf ----------------------------------------------------------------------------------
def _list(items: list[str]) -> str:
    return " ".join(f'"{x}"' if " " in x else x for x in items)


def smb_conf(cfg: FilesConfig, interfaces: list[str], nb_name: str, base: Path,
             paths: dict[str, Path] | None = None) -> str:
    any_guest = any(s.guest != "none" and s.enabled for s in cfg.shares)
    g = [
        "# generated by OutpostGate Pro - do not edit by hand",
        "[global]",
        f"   workgroup = {cfg.workgroup}",
        f"   netbios name = {nb_name}",
        f"   server string = {cfg.server_string}",
        "   server role = standalone server",
        "   security = user",
        f"   map to guest = {'Bad User' if any_guest else 'Never'}",
        f"   guest account = {SERVICE_USER}",
        f"   passdb backend = tdbsam:{base / 'private' / 'passdb.tdb'}",
        f"   private dir = {base / 'private'}",
        f"   state directory = {base / 'state'}",
        f"   cache directory = {base / 'cache'}",
        f"   lock directory = {base / 'lock'}",
        "   pid directory = /run/samba",
        f"   interfaces = lo {' '.join(interfaces)}",
        "   bind interfaces only = yes",
        f"   server min protocol = {cfg.min_protocol}",
        "   unix charset = UTF-8",
        "   load printers = no",
        "   printing = bsd",
        "   printcap name = /dev/null",
        "   disable spoolss = yes",
        "   usershare max shares = 0",
        "   log level = 1",
        "   logging = file",
        f"   log file = {base / 'log'}/%m.log",
        "   max log size = 1000",
    ]
    if cfg.netbios:
        g.append("   disable netbios = no")
    else:
        g += ["   disable netbios = yes", "   smb ports = 445"]
    if any(s.macos and s.enabled for s in cfg.shares):
        g += ["   fruit:metadata = stream", "   fruit:model = MacSamba", "   fruit:nfs_aces = no"]
    out = g + [""]
    for s in cfg.shares:
        if not s.enabled:
            continue
        path = (paths or {}).get(s.name) or share_path(s)
        lines = [f"[{s.name}]", f"   path = {path}"]
        if s.comment:
            lines.append(f"   comment = {s.comment}")
        lines += [f"   browseable = {'yes' if s.browseable else 'no'}",
                  f"   force user = {SERVICE_USER}", f"   force group = {SERVICE_USER}",
                  "   create mask = 0664", "   directory mask = 2775"]
        if s.guest != "none":
            lines.append("   guest ok = yes")
        else:
            lines.append(f"   valid users = {_list(s.read_users + s.write_users)}")
        if s.guest == "write":
            lines.append("   read only = no")
        else:
            lines.append("   read only = yes")
            if s.write_users:
                lines.append(f"   write list = {_list(s.write_users)}")
        if s.read_users and s.guest == "none":
            lines.append(f"   read list = {_list(s.read_users)}")
        vfs = []
        if s.macos:
            vfs += ["catia", "fruit", "streams_xattr"]
        if s.recycle:
            vfs.append("recycle")
            lines += ["   recycle:repository = .recycle/%U", "   recycle:keeptree = yes",
                      "   recycle:versions = yes", "   recycle:touch = yes",
                      "   recycle:exclude = *.tmp,~$*,*.temp", "   recycle:exclude_dir = .recycle"]
        if vfs:
            lines.append(f"   vfs objects = {' '.join(vfs)}")
        if s.hide_dot_files:
            lines.append("   hide dot files = yes")
        out += lines + [""]
    return "\n".join(out)


# --- Unix-учётки ---------------------------------------------------------------------------------
def _exists_user(name: str) -> pwd.struct_passwd | None:
    try:
        return pwd.getpwnam(name)
    except KeyError:
        return None


def _exists_group(name: str) -> grp.struct_group | None:
    try:
        return grp.getgrnam(name)
    except KeyError:
        return None


def sync_accounts(cfg: FilesConfig) -> None:
    """Unix-учётки под пользователей Samba (в контейнере их нет после пересоздания)."""
    if not _exists_group(SERVICE_USER):
        _run(["groupadd", "-g", str(FIRST_UID - 1), SERVICE_USER])
    if not _exists_user(SERVICE_USER):
        _run(["useradd", "-M", "-N", "-g", SERVICE_USER, "-u", str(FIRST_UID - 1),
              "-s", "/usr/sbin/nologin", "-d", "/nonexistent", SERVICE_USER])
    wanted_groups = {g.name: g.gid for g in cfg.groups}
    for name, gid in wanted_groups.items():
        if not _exists_group(name):
            _run(["groupadd", "-g", str(gid), name])
    for u in cfg.users:
        groups = ",".join(u.groups)
        if _exists_user(u.name):
            _run(["usermod", "-G", groups, "-c", u.full_name or "", u.name])
        else:
            cmd = ["useradd", "-M", "-N", "-g", SERVICE_USER, "-u", str(u.uid), "-s", "/usr/sbin/nologin",
                   "-d", "/nonexistent", "-c", u.full_name or ""]
            if groups:
                cmd += ["-G", groups]
            _run(cmd + [u.name])
    # лишние (удалённые из настроек) — только из нашего диапазона
    keep_users = {u.name for u in cfg.users} | {SERVICE_USER}
    for p in pwd.getpwall():
        if p.pw_uid >= FIRST_UID and p.pw_name not in keep_users:
            _run(["smbpasswd", *_smbpasswd_conf(), "-x", p.pw_name], check=False)
            _run(["userdel", p.pw_name], check=False)
    for gr in grp.getgrall():
        if gr.gr_gid >= FIRST_UID and gr.gr_name not in wanted_groups:
            _run(["groupdel", gr.gr_name], check=False)


def _smb_env_conf() -> list[str]:
    """pdbedit, smbstatus: -s <файл>."""
    return ["-s", str(_data("smb.conf"))]


def _smbpasswd_conf() -> list[str]:
    """smbpasswd: у него -s — «читать пароль из stdin», а файл настроек — -c."""
    return ["-c", str(_data("smb.conf"))]


def _ensure_passdb() -> None:
    """Сервер может быть ещё выключен — пароль всё равно сохраняется (учётка, база, smb.conf)."""
    cfg = get_config()
    _prepare_dirs()
    sync_accounts(cfg)
    if not _data("smb.conf").exists():
        _data("smb.conf").write_text(smb_conf(cfg, [], netbios_name(cfg), _data()))


def set_password(name: str, password: str) -> None:
    if "\n" in password:
        raise FilesError(400, "пароль: одной строкой")
    if installed():
        _ensure_passdb()
    _run(["smbpasswd", *_smbpasswd_conf(), "-s", "-a", name], input=f"{password}\n{password}\n")


def _set_enabled(name: str, on: bool) -> None:
    _run(["smbpasswd", *_smbpasswd_conf(), "-e" if on else "-d", name], check=False)


def users_with_password() -> set[str]:
    if not shutil.which("pdbedit") or not _data("smb.conf").exists():
        return set()
    r = _run(["pdbedit", *_smb_env_conf(), "-L"], check=False)
    return {l.split(":")[0] for l in r.stdout.splitlines() if ":" in l}


# --- процессы ----------------------------------------------------------------------------------
def installed() -> bool:
    return shutil.which("smbd") is not None


def running() -> bool:
    return _smbd.running()


def _prepare_dirs() -> None:
    for d in ("private", "state", "cache", "lock", "log"):
        _data(d).mkdir(parents=True, exist_ok=True)
    os.chmod(_data("private"), 0o700)
    Path("/run/samba").mkdir(parents=True, exist_ok=True)
    data_volume().mkdir(parents=True, exist_ok=True)


def _ensure_share_dirs(cfg: FilesConfig) -> None:
    owner = _exists_user(SERVICE_USER)
    for s in cfg.shares:
        if not s.enabled:
            continue
        vol = volume_path(s.volume)
        if s.volume != "data" and not os.path.ismount(vol):
            raise FilesError(400, f"папка {s.name}: диск {s.volume} не подключён")
        p = share_path(s)
        p.mkdir(parents=True, exist_ok=True)
        if owner:
            try:
                os.chown(p, owner.pw_uid, owner.pw_gid)
                os.chmod(p, 0o2775)
            except PermissionError:
                pass          # NTFS/exFAT: владелец задан при монтировании


def apply(cfg: FilesConfig | None = None) -> None:
    cfg = cfg or get_config()
    with _lock:
        segs = _segments(cfg) if cfg.enabled else []
        if not segs:
            for p in (_nmbd, _smbd):
                p.stop()
            return
        if not installed():
            raise FilesError(500, "нет Samba в образе — пересоберите образ (docker compose build)")
        _prepare_dirs()
        sync_accounts(cfg)
        _ensure_share_dirs(cfg)
        text = smb_conf(cfg, [s.bridge for s in segs], netbios_name(cfg), _data())
        fd, tmp = tempfile.mkstemp(dir=_data(), prefix=".smb.", suffix=".conf")
        with os.fdopen(fd, "w") as f:
            f.write(text)
        r = _run(["testparm", "-s", "--suppress-prompt", tmp], check=False)
        if r.returncode != 0:
            Path(tmp).unlink(missing_ok=True)
            raise FilesError(400, "Samba не приняла настройки: " + " ".join(r.stderr.split())[-300:])
        os.replace(tmp, _data("smb.conf"))
        for u in cfg.users:
            _set_enabled(u.name, u.enabled)
        conf = str(_data("smb.conf"))
        # SIGHUP только перечитывает конфиг и не меняет адреса, на которых слушает smbd:
        # снятый сегмент продолжал обслуживаться. Поэтому процессы перезапускаются.
        # Samba при остановке шлёт SIGTERM всей своей группе процессов, поэтому
        # smbd/nmbd запускаются в отдельной сессии (new_session=True), иначе
        # вместе с ними останавливается весь контейнер.
        _smbd.stop()
        _smbd.start(["smbd", "--foreground", "--no-process-group", "--debug-stdout", "-s", conf], new_session=True)
        _nmbd.stop()
        if cfg.netbios:
            _nmbd.start(["nmbd", "--foreground", "--no-process-group", "--debug-stdout", "-s", conf], new_session=True)


def update(new: FilesConfig) -> FilesStatus:
    """Сохранить настройки целиком и применить; ошибка — откат."""
    old = get_config()
    # пароли не в конфиге: uid/gid сохраняем от старых записей с тем же именем
    uids = {u.name: u.uid for u in old.users}
    gids = {g.name: g.gid for g in old.groups}
    for u in new.users:
        u.uid = u.uid or uids.get(u.name)
    for g in new.groups:
        g.gid = g.gid or gids.get(g.name)
    new = assign_ids(new)
    _check_disks(new, old)
    raw_old = store.load().get("files")
    with _lock:
        _save(new)
        try:
            apply(new)
        except FilesError:
            with store.transaction() as data:
                if raw_old is None:
                    data.pop("files", None)
                else:
                    data["files"] = raw_old
            try:
                apply()
            except FilesError as e:
                print(f"[files] ERROR: откат не удался: {e.message}")
            raise
    return status()


def _check_disks(new: FilesConfig, old: FilesConfig) -> None:
    """Список дисков меняется только через подключение и отключение."""
    if [d.model_dump() for d in new.disks] != [d.model_dump() for d in old.disks]:
        new.disks = old.disks
        new_vols = {"data"} | {d.name for d in new.disks}
        for s in new.shares:
            if s.volume not in new_vols:
                raise FilesError(400, f"папка {s.name}: нет тома {s.volume}")


def add_user(req: UserCreate) -> FilesStatus:
    cfg = get_config()
    if any(u.name == req.name for u in cfg.users):
        raise FilesError(409, f"пользователь {req.name} уже есть")
    cfg.users.append(FileUser(**req.model_dump(exclude={"password", "uid"})))
    update(cfg)
    try:
        set_password(req.name, req.password)
    except FilesError:
        cfg = get_config()
        cfg.users = [u for u in cfg.users if u.name != req.name]
        update(cfg)
        raise
    return status()


def change_password(name: str, password: str) -> FilesStatus:
    if not any(u.name == name for u in get_config().users):
        raise FilesError(404, f"нет пользователя {name}")
    set_password(name, password)
    return status()


def apply_startup() -> None:
    try:
        automount()
    except FilesError as e:
        print(f"[files] WARNING: диски: {e.message}")
    try:
        apply()
    except FilesError as e:
        print(f"[files] ERROR: {e.message}")


def stop() -> None:
    _nmbd.stop()
    _smbd.stop()


# --- диски -------------------------------------------------------------------------------------
def _mounted_majmin(mountinfo: str) -> set[str]:
    """Устройства (major:minor), на которых что-то смонтировано в этом контейнере —
    в том числе диск самого сервера (на нём лежат /etc/hosts и data/ контейнера)."""
    out = set()
    for line in mountinfo.splitlines():
        parts = line.split()
        if len(parts) > 2 and ":" in parts[2] and not parts[2].startswith("0:"):
            out.add(parts[2])
    return out


def parse_devices(lsblk: dict, used_majmin: set[str], mounted: dict[str, str]) -> list[BlockDevice]:
    """lsblk -J -b → список дисков и разделов. system=True: диск сервера и всё на нём."""
    out = []

    def walk(node, parent=None):
        if node.get("type") not in ("disk", "part"):
            for ch in node.get("children") or []:
                walk(ch, parent)
            return
        name = node["name"]
        if re.match(r"^(loop|ram|zram|sr|fd)", name):
            return
        dev = BlockDevice(
            name=name, path=node.get("path") or f"/dev/{name}", type=node["type"], size=int(node.get("size") or 0),
            fstype=node.get("fstype"), label=node.get("label"), uuid=node.get("uuid"),
            model=(node.get("model") or "").strip() or None, transport=node.get("tran"),
            removable=bool(node.get("rm")), parent=parent,
            system=node.get("maj:min") in used_majmin, mounted_as=mounted.get(node.get("uuid") or ""))
        out.append(dev)
        for ch in node.get("children") or []:
            walk(ch, name)

    for n in lsblk.get("blockdevices", []):
        walk(n)
    # диск системный, если системный хоть один его раздел
    sys_disks = {d.parent for d in out if d.system and d.parent}
    for d in out:
        if d.name in sys_disks or (d.parent in sys_disks):
            d.system = True
    return out


def devices() -> list[BlockDevice]:
    if not disks_allowed():
        return []
    r = _run(["lsblk", "-J", "-b", "-o", "NAME,PATH,SIZE,TYPE,FSTYPE,LABEL,UUID,MODEL,TRAN,RM,MAJ:MIN"], check=False)
    try:
        data = json.loads(r.stdout or "{}")
    except ValueError:
        return []
    used = _mounted_majmin(Path("/proc/self/mountinfo").read_text())
    cfg = get_config()
    mounted = {d.uuid: d.name for d in cfg.disks if os.path.ismount(DISKS_ROOT / d.name)}
    devs = parse_devices(data, used - _our_majmin(cfg), mounted)
    for d in devs:
        if d.mounted_as:
            try:
                u = shutil.disk_usage(DISKS_ROOT / d.mounted_as)
                d.used, d.free = u.used, u.free
            except OSError:
                pass
    return devs


def _our_majmin(cfg: FilesConfig) -> set[str]:
    """Наши же подключённые диски не считаются «системными»."""
    out = set()
    for d in cfg.disks:
        try:
            st = os.stat(DISKS_ROOT / d.name)
            if os.path.ismount(DISKS_ROOT / d.name):
                out.add(f"{os.major(st.st_dev)}:{os.minor(st.st_dev)}")
        except OSError:
            pass
    return out


def mount_options(fstype: str, read_only: bool) -> tuple[str, str]:
    """(тип для mount, опции)."""
    owner = _exists_user(SERVICE_USER)
    uid, gid = (owner.pw_uid, owner.pw_gid) if owner else (FIRST_UID - 1, FIRST_UID - 1)
    opts = ["ro" if read_only else "rw", "noatime"]
    if fstype in FOREIGN_FS:
        opts += [f"uid={uid}", f"gid={gid}", "umask=002"]
        fstype = "ntfs3" if fstype == "ntfs" else fstype
    return fstype, ",".join(opts)


def _mount(d: DiskMount, fstype: str) -> None:
    target = DISKS_ROOT / d.name
    if os.path.ismount(target):
        return
    target.mkdir(parents=True, exist_ok=True)
    t, opts = mount_options(fstype, d.read_only)
    _run(["mount", "-t", t, "-o", opts, f"UUID={d.uuid}", str(target)])
    if fstype not in FOREIGN_FS and not d.read_only:
        owner = _exists_user(SERVICE_USER)
        if owner:
            os.chown(target, owner.pw_uid, owner.pw_gid)
            os.chmod(target, 0o2775)


def mount(req: MountRequest) -> FilesStatus:
    if not disks_allowed():
        raise FilesError(403, "диски доступны только в режиме host (роутер на сервере)")
    dev = next((d for d in devices() if d.uuid == req.uuid), None)
    if not dev:
        raise FilesError(404, "раздел не найден — переподключите диск и обновите список")
    if dev.system:
        raise FilesError(400, f"{dev.path}: на этом диске стоит сам сервер — его подключать нельзя")
    if not dev.fstype or dev.fstype not in FSTYPES:
        raise FilesError(400, f"{dev.path}: файловая система {dev.fstype or 'не найдена'} — нужен ext4, xfs, btrfs, NTFS, exFAT или FAT32")
    cfg = get_config()
    item = DiskMount(name=req.name, uuid=req.uuid, fstype=dev.fstype, automount=req.automount, read_only=req.read_only)
    if any(d.name == item.name for d in cfg.disks):
        raise FilesError(409, f"диск с именем {item.name} уже есть")
    if any(d.uuid == item.uuid for d in cfg.disks):
        raise FilesError(409, "этот раздел уже подключён")
    sync_accounts(cfg)
    _mount(item, dev.fstype)
    cfg.disks.append(item)
    _save(cfg)
    return status()


def unmount(name: str) -> FilesStatus:
    cfg = get_config()
    d = next((x for x in cfg.disks if x.name == name), None)
    if not d:
        raise FilesError(404, f"нет диска {name}")
    users = [s.name for s in cfg.shares if s.volume == name]
    if users:
        raise FilesError(400, f"диск используют папки: {', '.join(users)} — сначала перенесите или удалите их")
    target = DISKS_ROOT / name
    if os.path.ismount(target):
        r = _run(["umount", str(target)], check=False)
        if r.returncode != 0:
            raise FilesError(409, f"диск занят — закройте файлы и повторите ({' '.join(r.stderr.split())[-120:]})")
    try:
        target.rmdir()
    except OSError:
        pass
    cfg.disks = [x for x in cfg.disks if x.name != name]
    _save(cfg)
    return status()


def automount() -> None:
    if not disks_allowed():
        return
    cfg = get_config()
    if not cfg.disks:
        return
    sync_accounts(cfg)
    present = {d.uuid: d for d in devices()}
    for d in cfg.disks:
        if not d.automount:
            continue
        dev = present.get(d.uuid)
        if not dev:
            print(f"[files] диск {d.name} (UUID {d.uuid}) не найден — пропускаю")
            continue
        try:
            _mount(d, dev.fstype or d.fstype or "ext4")
            print(f"[files] диск {d.name} подключён: {dev.path}")
        except FilesError as e:
            print(f"[files] WARNING: {d.name}: {e.message}")


def format_device(req: FormatRequest) -> FilesStatus:
    """Стереть устройство и создать ext4. Только не системное и не подключённое."""
    if not disks_allowed():
        raise FilesError(403, "диски доступны только в режиме host (роутер на сервере)")
    if req.confirm != req.device:
        raise FilesError(400, "подтверждение не совпадает с именем устройства")
    devs = devices()
    dev = next((d for d in devs if d.path == req.device), None)
    if not dev:
        raise FilesError(404, f"нет устройства {req.device}")
    family = [d for d in devs if d.name == dev.name or d.parent == dev.name]
    if any(d.system for d in family):
        raise FilesError(400, f"{dev.path}: на этом диске стоит сам сервер — форматировать нельзя")
    if any(d.mounted_as for d in family):
        raise FilesError(400, f"{dev.path}: сначала отключите диск")
    _run(["wipefs", "-a", dev.path], timeout=120)
    target = dev.path
    if dev.type == "disk":
        _run(["sfdisk", "--wipe", "always", dev.path], input="label: gpt\n,,L\n", timeout=120)
        _run(["udevadm", "settle"], check=False)
        parts = [d for d in devices() if d.parent == dev.name]
        if not parts:
            raise FilesError(500, f"{dev.path}: раздел не появился — переподключите диск")
        target = parts[0].path
    _run(["mkfs.ext4", "-F", "-L", req.label, target], timeout=1800)
    print(f"[files] {target} отформатирован в ext4 ({req.label})")
    return status()


