def parse_sessions(data: dict) -> list[Session]:
    sessions = data.get("sessions") or {}
    tcons = data.get("tcons") or {}
    opens: dict[str, int] = {}
    for f in (data.get("open_files") or {}).values():
        for o in (f.get("opens") or {}).values():
            sid = str((o.get("server_id") or {}).get("pid") or "")
            opens[sid] = opens.get(sid, 0) + 1
    out = []
    for sid, s in sessions.items():
        shares = sorted({t.get("service") for t in tcons.values() if str(t.get("session_id")) == str(sid) and t.get("service")})
        pid = str((s.get("server_id") or {}).get("pid") or "")
        out.append(Session(user=s.get("username") or "?", machine=s.get("remote_machine") or s.get("hostname") or "?",
                           protocol=s.get("session_dialect"), share=", ".join(shares) or None,
                           since=next((t.get("connected_at") for t in tcons.values()
                                       if str(t.get("session_id")) == str(sid)), None),
                           open_files=opens.get(pid, 0)))
    return out


def sessions() -> list[Session]:
    if not running() or not shutil.which("smbstatus"):
        return []
    r = _run(["smbstatus", *_smb_env_conf(), "--json"], check=False, timeout=10)
    try:
        return parse_sessions(json.loads(r.stdout or "{}"))
    except ValueError:
        return []


def volumes(cfg: FilesConfig) -> list[Volume]:
    out = []
    for name in ["data"] + [d.name for d in cfg.disks]:
        p = volume_path(name)
        mounted = name == "data" or os.path.ismount(p)
        v = Volume(name=name, path=str(p), mounted=mounted)
        if mounted and p.exists():
            try:
                u = shutil.disk_usage(p)
                v.size, v.free = u.total, u.free
            except OSError:
                pass
        out.append(v)
    return out


def status() -> FilesStatus:
    from app.services import lan
    cfg = get_config()
    segs = _segments(cfg)
    st = FilesStatus(config=cfg, installed=installed(), running=running(), netbios_name=netbios_name(cfg),
                     listen=[s.router_ip for s in segs] if cfg.enabled else [],
                     disks_allowed=disks_allowed(), volumes=volumes(cfg),
                     segments=[{"id": s.id, "name": s.name, "address": s.address, "enabled": s.enabled}
                               for s in lan.segments()])
    try:
        st.devices = devices()
    except FilesError as e:
        st.error = e.message
    st.sessions = sessions()
    with_pw = users_with_password()
    st.users_without_password = [u.name for u in cfg.users if running() and u.name not in with_pw]
    if cfg.enabled and not st.installed:
        st.error = "нет Samba в образе — пересоберите образ (docker compose build)"
    elif cfg.enabled and segs and not st.running:
        st.error = "Samba не запущена — см. docker logs"
    elif cfg.enabled and not segs:
        st.error = "нет включённых сегментов LAN для файлсервера"
    return st
