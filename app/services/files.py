"""
Файловый сервер Samba: общие папки для сегментов LAN.

router.yaml (секция files:) — источник правды для настроек, пользователей, групп, папок
и дисков. Роутер генерирует smb.conf целиком, проверяет его (testparm) и применяет без
разрыва подключений (SIGHUP). Пароли хранит сама Samba (data/samba/private/passdb.tdb).

Права: все файлы на диске принадлежат служебной учётке og-files (force user), а кто что
может — решает Samba (valid users / read list / write list). Так не бывает ситуаций
«файл создал Иван — Мария его не может изменить».

Диски: только в режиме host (контейнер видит диски сервера). Разделы монтируются по UUID
в /mnt/disks/<имя>; диск, на котором стоит сам сервер, роутер не трогает.
"""
