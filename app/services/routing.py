# --- FRR -------------------------------------------------------------------------------------
def installed() -> bool:
    return Path(FRRINIT).exists() and shutil.which("vtysh") is not None


def _run(cmd: list[str], timeout: int = 30) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError as e:
        raise RoutingError(500, f"нет программы {cmd[0]} — пересоберите образ") from e
    except subprocess.TimeoutExpired as e:
        raise RoutingError(500, f"{cmd[0]}: нет ответа за {timeout} с") from e


def _write(path: Path, text: str, mode: int = 0o640) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, mode)
    try:
        shutil.chown(tmp, "frr", "frr")      # демоны FRR работают от пользователя frr
    except (LookupError, PermissionError, OSError):
        pass
    os.replace(tmp, path)


def check(text: str) -> None:
    """Проверить frr.conf до применения (vtysh --dryrun). Без FRR — пропускается."""
    if not shutil.which("vtysh"):
        return
    fd, tmp = tempfile.mkstemp(prefix="frr-check-", suffix=".conf")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        r = _run(["vtysh", "--dryrun", "--inputfile", tmp])
        if r.returncode != 0:
            msg = " ".join((r.stderr or r.stdout).split())[:400]
            raise RoutingError(400, f"FRR не принял конфигурацию: {msg}")
    finally:
        Path(tmp).unlink(missing_ok=True)


def running() -> bool:
    if not installed():
        return False
    r = subprocess.run(["pgrep", "-x", "zebra"], capture_output=True)
    return r.returncode == 0


def _frrinit(action: str) -> None:
    # вывод — во временный файл, не в pipe: демоны FRR уходят в фон и могли бы
    # унаследовать pipe, и тогда subprocess ждал бы их завершения до таймаута
    with tempfile.TemporaryFile("w+") as log:
        try:
            rc = subprocess.run([FRRINIT, action], stdout=log, stderr=subprocess.STDOUT,
                                stdin=subprocess.DEVNULL, timeout=90).returncode
        except FileNotFoundError as e:
            raise RoutingError(500, "нет FRRouting в образе — пересоберите образ (docker compose build)") from e
        except subprocess.TimeoutExpired as e:
            raise RoutingError(500, f"FRR {action}: нет ответа за 90 с") from e
        log.seek(0)
        text = log.read().strip()
    if text:
        print(f"[routing] frrinit {action}: {text[-500:]}")
    if rc != 0:
        raise RoutingError(500, f"FRR {action}: {text[-400:] or f'код {rc}'}")


def apply(cfg: RoutingConfig | None = None) -> None:
    """Привести FRR к настройкам."""
    cfg = cfg or get_config()
    with _lock:
        if not active(cfg):
            if running():
                _frrinit("stop")
                print("[routing] OSPF и BGP выключены — FRR остановлен")
            return
        if not installed():
            raise RoutingError(500, "нет FRRouting в образе — пересоберите образ (docker compose build)")
        text = frr_conf(cfg, _hostname())
        check(text)
        _write(FRR_DIR / "daemons", daemons_file(), 0o644)
        _write(FRR_DIR / "vtysh.conf", "service integrated-vtysh-config\n", 0o644)
        _write(FRR_DIR / "frr.conf", text)
        if not running():
            _frrinit("start")
            print("[routing] FRR запущен")
            return
        reloaded = False
        if Path(FRR_RELOAD).exists():
            r = _run([FRR_RELOAD, "--reload", str(FRR_DIR / "frr.conf")], timeout=60)
            reloaded = r.returncode == 0
            if not reloaded:
                print(f"[routing] WARNING: frr-reload: {(r.stderr or r.stdout).strip()[-300:]}")
        if not reloaded:
            _frrinit("restart")
            print("[routing] FRR перезапущен")
        else:
            print("[routing] конфигурация FRR применена без перезапуска")


SECRET = "********"   # так API показывает заданные пароли; пришло обратно — значит, не менять


def masked(cfg: RoutingConfig) -> RoutingConfig:
    c = cfg.model_copy(deep=True)
    for i in c.ospf.interfaces:
        if i.auth_key:
            i.auth_key = SECRET
    for n in c.bgp.neighbors:
        if n.password:
            n.password = SECRET
    return c


def keep_secrets(new: RoutingConfig, old: RoutingConfig) -> RoutingConfig:
    keys = {i.name: i.auth_key for i in old.ospf.interfaces}
    pws = {n.address: n.password for n in old.bgp.neighbors}
    c = new.model_copy(deep=True)
    for i in c.ospf.interfaces:
        if i.auth_key == SECRET:
            i.auth_key = keys.get(i.name)
    for n in c.bgp.neighbors:
        if n.password == SECRET:
            n.password = pws.get(n.address)
    return c


def update(new: RoutingConfig) -> RoutingStatus:
    from app.services import firewall, vpn
    new = keep_secrets(new, get_config())
    old = store.load().get("routing")
    with store.transaction() as data:
        data["routing"] = new.to_yaml()
    try:
        apply(new)
    except RoutingError:
        with store.transaction() as data:
            if old is None:
                data.pop("routing", None)
            else:
                data["routing"] = old
        try:
            apply()
        except RoutingError as e:
            print(f"[routing] ERROR: откат не удался: {e}")
        raise
    for step in (firewall.refresh, vpn.sync_allowed_ips):   # протоколы в фаерволе, multicast в WireGuard
        try:
            step()
        except Exception as e:  # маршрутизация уже применена; ошибка — в журнал
            print(f"[routing] WARNING: {step.__module__}.{step.__name__}: {e}")
    return status()


def apply_startup() -> None:
    try:
        apply()
    except RoutingError as e:
        print(f"[routing] ERROR: {e.message}")


def stop() -> None:
    try:
        if running():
            _frrinit("stop")
    except RoutingError as e:
        print(f"[routing] WARNING: {e.message}")


# --- для фаервола и VPN ----------------------------------------------------------------------
def ospf_interfaces(cfg: RoutingConfig | None = None) -> list[str]:
    """Интерфейсы, где OSPF ищет соседей: явно перечисленные (не пассивные)
    и все интерфейсы, адреса которых попадают в сети OSPF."""
    cfg = cfg or get_config()
    o = cfg.ospf
    if not o.enabled:
        return []
    passive = {i.name for i in o.interfaces if i.passive}
    nets = [ipaddress.ip_network(n.network) for n in o.networks]
    found = []
    try:
        kernel = netlink.kernel_ipv4_addresses()
    except Exception:
        kernel = []
    for ifname, cidr in kernel:
        ip = ipaddress.ip_interface(cidr).ip
        if any(ip in n for n in nets) and ifname not in found:
            found.append(ifname)
    for i in o.interfaces:
        if i.name not in found:
            found.append(i.name)
    explicit_active = {i.name for i in o.interfaces if not i.passive}
    if o.passive_default:
        return [n for n in found if n in explicit_active]
    return [n for n in found if n not in passive]


def bgp_peers(cfg: RoutingConfig | None = None) -> list[str]:
    cfg = cfg or get_config()
    return [n.address for n in cfg.bgp.neighbors if n.enabled] if cfg.bgp.enabled else []


# --- состояние -------------------------------------------------------------------------------
def _vtysh_json(command: str):
    try:
        r = _run(["vtysh", "-c", command], timeout=10)
    except RoutingError:
        return None
    if r.returncode != 0:
        return None
    try:
        return json.loads(r.stdout or "null")
    except ValueError:
        return None


def _ms(v) -> str | None:
    """Миллисекунды -> «1h02m03s»."""
    if not isinstance(v, (int, float)):
        return v if isinstance(v, str) else None
    s = int(v) // 1000
    d, s = divmod(s, 86400)
    h, s = divmod(s, 3600)
    m, s = divmod(s, 60)
    return (f"{d}d" if d else "") + (f"{h}h" if d or h else "") + f"{m:02d}m{s:02d}s"


def parse_ospf_neighbors(data) -> list[OspfNeighborView]:
    out = []
    neighbors = (data or {}).get("neighbors", {}) if isinstance(data, dict) else {}
    for rid, items in neighbors.items():
        for n in items if isinstance(items, list) else [items]:
            iface = n.get("ifaceName") or n.get("interfaceName")
            out.append(OspfNeighborView(
                router_id=rid,
                address=n.get("ifaceAddress") or n.get("address"),
                interface=iface.split(":")[0] if iface else None,
                state=n.get("nbrState") or n.get("state") or "",
                priority=n.get("nbrPriority", n.get("priority")),
                uptime=_ms(n.get("upTimeInMsec")) or n.get("upTime"),
                dead_time=_ms(n.get("routerDeadIntervalTimerDueMsec", n.get("deadTimeMsecs"))),
            ))
    return out


def parse_bgp_summary(data, cfg: RoutingConfig) -> list[BgpPeerView]:
    peers = {}
    if isinstance(data, dict):
        af = data.get("ipv4Unicast") or data
        peers = af.get("peers", {}) if isinstance(af, dict) else {}
    out = []
    for n in cfg.bgp.neighbors:
        p = peers.get(n.address, {})
        state = p.get("state") or ("Idle (Admin)" if not n.enabled else "—")
        out.append(BgpPeerView(
            address=n.address, remote_as=p.get("remoteAs", n.remote_as), description=n.description,
            state=state, uptime=p.get("peerUptime") if state == "Established" else None,
            prefixes_received=p.get("pfxRcd", p.get("prefixReceivedCount")),
            prefixes_sent=p.get("pfxSnt"), enabled=n.enabled))
    return out


def parse_routes(data) -> list[RouteView]:
    out = []
    if not isinstance(data, dict):
        return out
    for prefix, entries in data.items():
        for e in entries if isinstance(entries, list) else []:
            if e.get("protocol") not in PROTOCOLS:
                continue
            hops = [h for h in e.get("nexthops", []) if h.get("active", True)] or e.get("nexthops", [])
            h = hops[0] if hops else {}
            out.append(RouteView(prefix=e.get("prefix", prefix), protocol=e["protocol"],
                                 nexthop=h.get("ip"), interface=h.get("interfaceName"),
                                 distance=e.get("distance"), metric=e.get("metric"),
                                 selected=bool(e.get("selected"))))
    out.sort(key=lambda r: (r.protocol, ipaddress.ip_network(r.prefix, strict=False)))
    return out


def _interfaces() -> list[str]:
    try:
        return sorted(n for n in netlink.link_names() if n != "lo")
    except Exception:
        return []


def status() -> RoutingStatus:
    cfg = get_config()
    st = RoutingStatus(config=masked(cfg), installed=installed(), interfaces=_interfaces())
    if not st.installed:
        if active(cfg):
            st.error = "нет FRRouting в образе — пересоберите образ (docker compose build)"
        return st
    st.running = running()
    if not st.running:
        if active(cfg):
            st.error = "FRR не запущен — см. docker logs"
        return st
    if cfg.ospf.enabled:
        st.ospf_neighbors = parse_ospf_neighbors(_vtysh_json("show ip ospf neighbor json"))
        info = _vtysh_json("show ip ospf json") or {}
        st.router_id = info.get("routerId")
    if cfg.bgp.enabled:
        summary = _vtysh_json("show bgp ipv4 unicast summary json")
        st.bgp_peers = parse_bgp_summary(summary, cfg)
        if isinstance(summary, dict):
            st.router_id = st.router_id or (summary.get("ipv4Unicast") or summary).get("routerId")
    st.routes = parse_routes(_vtysh_json("show ip route json"))
    return st
