"""
Динамическая маршрутизация: OSPF и BGP на FRRouting.

router.yaml (секция routing:) — источник правды. Роутер генерирует /etc/frr/frr.conf
целиком, проверяет его (vtysh --dryrun) и применяет:
  * FRR не запущен, а OSPF или BGP включены — запуск (frrinit.sh start);
  * FRR запущен — мягкая перезагрузка (frr-reload.py: соседи не сбрасываются,
    если их настройки не менялись); не вышло — перезапуск;
  * OSPF и BGP выключены — FRR останавливается, его маршруты уходят из ядра.
Состояние (соседи, маршруты) — из vtysh в формате JSON.
"""
from __future__ import annotations

import ipaddress
import json
import os
import re
import shutil
import subprocess
import tempfile
import threading
from pathlib import Path

from app.core.store import store
from app.models.routing import (BgpPeerView, OspfNeighborView, RouteView, RoutingConfig,
                                RoutingStatus)
from app.services import netlink

FRR_DIR = Path(os.getenv("FRR_DIR", "/etc/frr"))
FRRINIT = "/usr/lib/frr/frrinit.sh"
FRR_RELOAD = "/usr/lib/frr/frr-reload.py"
PROTOCOLS = ("ospf", "bgp")

_lock = threading.RLock()


class RoutingError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status
        self.message = message


# --- конфиг ----------------------------------------------------------------------------------
def get_config() -> RoutingConfig:
    return RoutingConfig.model_validate(store.load().get("routing") or {})


def active(cfg: RoutingConfig | None = None) -> bool:
    cfg = cfg or get_config()
    return cfg.ospf.enabled or cfg.bgp.enabled


def _hostname() -> str:
    ident = (store.load().get("system") or {}).get("identity") or "outpost-gate-pro"
    return re.sub(r"[^A-Za-z0-9-]", "-", ident)[:63] or "router"


def _nb_tag(i: int) -> str:
    return f"BGP-N{i}"


def frr_conf(cfg: RoutingConfig, hostname: str = "outpost-gate-pro") -> str:
    """Полный frr.conf из настроек. Пустые разделы не пишутся."""
    out = ["! generated by OutpostGate Pro - do not edit by hand",
           "frr defaults traditional", f"hostname {hostname}", "log file /var/log/frr/frr.log informational",
           "service integrated-vtysh-config", "!"]
    ospf, bgp = cfg.ospf, cfg.bgp

    # prefix-list для фильтров BGP
    if bgp.enabled:
        for i, n in enumerate(bgp.neighbors, 1):
            for direction, items in (("IN", n.prefix_in), ("OUT", n.prefix_out)):
                for seq, p in enumerate(items, 1):
                    out.append(f"ip prefix-list {_nb_tag(i)}-{direction} seq {seq * 5} permit {p}")
        if any(n.prefix_in or n.prefix_out for n in bgp.neighbors):
            out.append("!")

    # интерфейсы OSPF
    if ospf.enabled:
        for itf in ospf.interfaces:
            lines = []
            if itf.cost:
                lines.append(f" ip ospf cost {itf.cost}")
            if itf.network_type != "auto":
                lines.append(f" ip ospf network {itf.network_type}")
            if itf.hello != 10:
                lines.append(f" ip ospf hello-interval {itf.hello}")
            if itf.dead != 40:
                lines.append(f" ip ospf dead-interval {itf.dead}")
            if itf.priority is not None:
                lines.append(f" ip ospf priority {itf.priority}")
            if itf.auth_key:
                lines += [" ip ospf authentication message-digest",
                          f" ip ospf message-digest-key 1 md5 {itf.auth_key}"]
            # пассивность — на интерфейсе (FRR 8+: так, а не passive-interface IFNAME в router ospf)
            if itf.passive and not ospf.passive_default:
                lines.append(" ip ospf passive")
            elif not itf.passive and ospf.passive_default:
                lines.append(" no ip ospf passive")
            if lines:
                out += [f"interface {itf.name}", *lines, "exit", "!"]

        out.append("router ospf")
        if cfg.router_id:
            out.append(f" ospf router-id {cfg.router_id}")
        if ospf.passive_default:
            out.append(" passive-interface default")
        for n in ospf.networks:
            out.append(f" network {n.network} area {n.area}")
        for itf in ospf.interfaces:
            if itf.network_type == "non-broadcast" and itf.neighbor:
                out.append(f" neighbor {itf.neighbor}")
        for r in ospf.redistribute:
            out.append(f" redistribute {r}")
        if ospf.default_route == "always":
            out.append(" default-information originate always")
        elif ospf.default_route == "if-installed":
            out.append(" default-information originate")
        out += ["exit", "!"]

    # BGP
    if bgp.enabled:
        out.append(f"router bgp {bgp.asn}")
        if cfg.router_id:
            out.append(f" bgp router-id {cfg.router_id}")
        # FRR по умолчанию не отдаёт и не принимает eBGP-маршруты без политики — для офиса это лишнее
        out.append(" no bgp ebgp-requires-policy")
        for n in bgp.neighbors:
            a = n.address
            out.append(f" neighbor {a} remote-as {n.remote_as}")
            if n.description:
                out.append(f' neighbor {a} description {n.description}')
            if n.password:
                out.append(f" neighbor {a} password {n.password}")
            if n.multihop:
                out.append(f" neighbor {a} ebgp-multihop {n.multihop}")
            if n.update_source:
                out.append(f" neighbor {a} update-source {n.update_source}")
            if (n.keepalive, n.hold) != (60, 180):
                out.append(f" neighbor {a} timers {n.keepalive} {n.hold}")
            if not n.enabled:
                out.append(f" neighbor {a} shutdown")
        out.append(" !")
        out.append(" address-family ipv4 unicast")
        for net in bgp.networks:
            out.append(f"  network {net}")
        for r in bgp.redistribute:
            out.append(f"  redistribute {r}")
        for i, n in enumerate(bgp.neighbors, 1):
            if n.prefix_in:
                out.append(f"  neighbor {n.address} prefix-list {_nb_tag(i)}-IN in")
            if n.prefix_out:
                out.append(f"  neighbor {n.address} prefix-list {_nb_tag(i)}-OUT out")
        out += [" exit-address-family", "exit", "!"]

    out.append("end")
    return "\n".join(out) + "\n"


